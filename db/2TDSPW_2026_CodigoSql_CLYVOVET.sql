-- PROCEDIMENTO 1: JOIN entre TB_CONSULTA, TB_PET e TB_VETERINARIO (3 tabelas),
-- convertendo cada linha para JSON manualmente atraves da FN_MONTA_JSON (Funcao 1)
CREATE OR REPLACE PROCEDURE "PRC_CONSULTA_JSON"
IS
    CURSOR c_consultas IS
        SELECT co."Id"           AS consulta_id,
               co."DtConsulta"   AS dt_consulta,
               co."TpEvento"     AS tp_evento,
               co."Notificar"    AS notificar,
               p."NmPet"         AS nm_pet,
               p."DsEspecie"     AS ds_especie,
               p."DsRaca"        AS ds_raca,
               v."DsEmail"       AS vet_email
        FROM   "TB_CONSULTA" co
        JOIN   "TB_PET" p ON p."Id" = co."PetId"
        JOIN   "TB_VETERINARIO" v ON v."Id" = co."VeterinarioId"
        ORDER BY co."Id";

    v_chaves     "T_TAB_VARCHAR2";
    v_valores    "T_TAB_VARCHAR2";
    v_tipos      "T_TAB_VARCHAR2";
    v_json       VARCHAR2(4000);
    v_qtd_linhas NUMBER := 0;
BEGIN
    v_chaves := "T_TAB_VARCHAR2"('consulta_id','data_consulta','tipo_evento','notificar','pet_nome','pet_especie','pet_raca','veterinario_email');
    v_tipos  := "T_TAB_VARCHAR2"('N','S','S','N','S','S','S','S');

    FOR r IN c_consultas LOOP
        v_valores := "T_TAB_VARCHAR2"(
            TO_CHAR(r.consulta_id), r.dt_consulta, r.tp_evento, TO_CHAR(r.notificar),
            r.nm_pet, r.ds_especie, r.ds_raca, r.vet_email
        );

        v_json := "FN_MONTA_JSON"(v_chaves, v_valores, v_tipos);
        DBMS_OUTPUT.PUT_LINE(v_json);

        v_qtd_linhas := v_qtd_linhas + 1;
    END LOOP;

    -- Exceção 1: nenhuma consulta encontrada
    IF v_qtd_linhas = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('AVISO: nenhuma consulta cadastrada para gerar o JSON.');
    -- Exceção 2: erro de conversão de tipo (ex.: campo numerico invalido)
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: valor invalido ao converter dados da consulta para JSON.');
    -- Exceção 3: qualquer outro erro inesperado
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO INESPERADO em PRC_CONSULTA_JSON: ' || SQLERRM);
END;
/

-- PROCEDIMENTO 2: soma manual (sem ROLLUP/CUBE/GROUPING SETS) de QtMedicamento
-- agrupada por TratamentoId (categoria 1) e MedicamentoId (categoria 2), com
-- subtotal por TratamentoId e total geral ao final.
CREATE OR REPLACE PROCEDURE "PRC_RESUMO_TRATAMENTO_MEDICAMENTO"
IS
    CURSOR c_tratmed IS
        SELECT "TratamentoId", "MedicamentoId", "QtMedicamento"
        FROM   "TB_TRATAMENTO_MEDICAMENTO"
        ORDER BY "TratamentoId", "MedicamentoId";

    v_trat_atual   "TB_TRATAMENTO_MEDICAMENTO"."TratamentoId"%TYPE := NULL;
    v_subtotal     NUMBER := 0;
    v_total_geral  NUMBER := 0;
    v_qtd_linhas   NUMBER := 0;
    e_quantidade_invalida EXCEPTION;
BEGIN
    DBMS_OUTPUT.PUT_LINE(RPAD('Tratamento',12) || RPAD('Medicamento',13) || 'Qtd');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',10,'-') || '  ' || RPAD('-',10,'-') || '  ' || RPAD('-',7,'-'));

    FOR r IN c_tratmed LOOP

        -- Exceção 1 (regra de negocio): quantidade nao pode ser negativa
        IF r."QtMedicamento" < 0 THEN
            RAISE e_quantidade_invalida;
        END IF;

        -- quebra de controle: fechou um grupo de TratamentoId, imprime subtotal
        IF v_trat_atual IS NOT NULL AND r."TratamentoId" <> v_trat_atual THEN
            DBMS_OUTPUT.PUT_LINE(RPAD(' ',12) || RPAD('Sub Total',13) || TO_CHAR(v_subtotal));
            v_subtotal := 0;
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(TO_CHAR(r."TratamentoId"),12) || RPAD(TO_CHAR(r."MedicamentoId"),13) || TO_CHAR(r."QtMedicamento"));

        v_subtotal    := v_subtotal + r."QtMedicamento";
        v_total_geral := v_total_geral + r."QtMedicamento";
        v_trat_atual  := r."TratamentoId";
        v_qtd_linhas  := v_qtd_linhas + 1;
    END LOOP;

    -- Exceção 2: nenhuma linha na tabela de tratamento x medicamento
    IF v_qtd_linhas = 0 THEN
        RAISE NO_DATA_FOUND;
    END IF;

    -- imprime o subtotal do ultimo grupo e o total geral
    DBMS_OUTPUT.PUT_LINE(RPAD(' ',12) || RPAD('Sub Total',13) || TO_CHAR(v_subtotal));
    DBMS_OUTPUT.PUT_LINE(RPAD(' ',12) || RPAD('Total Geral',13) || TO_CHAR(v_total_geral));

EXCEPTION
    WHEN e_quantidade_invalida THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: foi encontrada uma quantidade de medicamento negativa (dado invalido).');
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('AVISO: nao ha registros em TB_TRATAMENTO_MEDICAMENTO para resumir.');
    -- Exceção 3: erro de conversão/aritmetico ao somar
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: valor invalido encontrado ao somar as quantidades.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO INESPERADO em PRC_RESUMO_TRATAMENTO_MEDICAMENTO: ' || SQLERRM);
END;
/

--------------------------------------------------------------------------------
-- BLOCO 6: TRIGGER DE AUDITORIA (DML) EM TB_CONSULTA
--------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER "TRG_AUDITORIA_CONSULTA"
AFTER INSERT OR UPDATE OR DELETE ON "TB_CONSULTA"
FOR EACH ROW
DECLARE
    v_tipo_operacao VARCHAR2(10);
    v_valores_old   VARCHAR2(4000);
    v_valores_new   VARCHAR2(4000);
BEGIN
    IF INSERTING THEN
        v_tipo_operacao := 'INSERT';
    ELSIF UPDATING THEN
        v_tipo_operacao := 'UPDATE';
    ELSIF DELETING THEN
        v_tipo_operacao := 'DELETE';
    END IF;

    -- captura os valores ANTERIORES (:OLD) em UPDATE/DELETE
    IF UPDATING OR DELETING THEN
        v_valores_old := 'Id=' || :OLD."Id" ||
                          ';DtConsulta=' || :OLD."DtConsulta" ||
                          ';TpEvento=' || :OLD."TpEvento" ||
                          ';Notificar=' || :OLD."Notificar" ||
                          ';PetId=' || :OLD."PetId" ||
                          ';VeterinarioId=' || :OLD."VeterinarioId";
    END IF;

    -- captura os valores NOVOS (:NEW) em INSERT/UPDATE
    IF INSERTING OR UPDATING THEN
        v_valores_new := 'Id=' || :NEW."Id" ||
                          ';DtConsulta=' || :NEW."DtConsulta" ||
                          ';TpEvento=' || :NEW."TpEvento" ||
                          ';Notificar=' || :NEW."Notificar" ||
                          ';PetId=' || :NEW."PetId" ||
                          ';VeterinarioId=' || :NEW."VeterinarioId";
    END IF;

    INSERT INTO "TB_AUDITORIA" ("NomeUsuario","TipoOperacao","DataHoraOperacao","ValoresAnteriores","ValoresNovos")
    VALUES (SYS_CONTEXT('USERENV','SESSION_USER'), v_tipo_operacao, SYSTIMESTAMP, v_valores_old, v_valores_new);

EXCEPTION
    WHEN OTHERS THEN
        -- nao deixa uma falha de auditoria derrubar a operacao original na TB_CONSULTA
        NULL;
END;
/

