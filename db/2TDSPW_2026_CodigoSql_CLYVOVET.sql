-- FUNCAO 1: recebe colunas (nomes/valores/tipos) de QUALQUER consulta relacional
-- e monta manualmente a string JSON correspondente, SEM usar TO_JSON, JSON_OBJECT,
-- JSON_VALUE, JSON_QUERY, JSON_TABLE ou qualquer funcao nativa de JSON do Oracle.
-- p_tipos: 'N' = valor numerico (sem aspas), 'S' = valor texto (com aspas, default)
CREATE OR REPLACE FUNCTION "FN_MONTA_JSON" (
    p_chaves  IN "T_TAB_VARCHAR2",
    p_valores IN "T_TAB_VARCHAR2",
    p_tipos   IN "T_TAB_VARCHAR2" DEFAULT NULL
) RETURN VARCHAR2
IS
    v_json          VARCHAR2(32000) := '{';
    v_valor_escapado VARCHAR2(4000);
    v_tipo          VARCHAR2(1);
    e_listas_vazias      EXCEPTION;
    e_tamanhos_diferentes EXCEPTION;
    e_tipo_invalido       EXCEPTION;
BEGIN
    -- Exceção 1: listas vazias ou nulas não fazem sentido para montar um JSON
    IF p_chaves IS NULL OR p_valores IS NULL OR p_chaves.COUNT = 0 THEN
        RAISE e_listas_vazias;
    END IF;

    -- Exceção 2: chaves e valores precisam ter a mesma quantidade de itens
    IF p_chaves.COUNT <> p_valores.COUNT THEN
        RAISE e_tamanhos_diferentes;
    END IF;

    FOR i IN 1 .. p_chaves.COUNT LOOP

        -- define o tipo do campo (S = string, N = numerico); default = S
        IF p_tipos IS NOT NULL AND p_tipos.COUNT = p_chaves.COUNT THEN
            v_tipo := p_tipos(i);
        ELSE
            v_tipo := 'S';
        END IF;

        IF v_tipo NOT IN ('S','N') THEN
            RAISE e_tipo_invalido;
        END IF;

        IF p_valores(i) IS NULL THEN
            v_json := v_json || '"' || p_chaves(i) || '":null';
        ELSIF v_tipo = 'N' THEN
            -- Exceção 3 (VALUE_ERROR nativa): valida se realmente é numérico
            v_json := v_json || '"' || p_chaves(i) || '":' || TO_CHAR(TO_NUMBER(p_valores(i)));
        ELSE
            -- escapa aspas duplas e barras invertidas manualmente (sem função de JSON)
            v_valor_escapado := REPLACE(REPLACE(p_valores(i), '\', '\\'), '"', '\"');
            v_json := v_json || '"' || p_chaves(i) || '":"' || v_valor_escapado || '"';
        END IF;

        IF i < p_chaves.COUNT THEN
            v_json := v_json || ',';
        END IF;
    END LOOP;

    v_json := v_json || '}';
    RETURN v_json;

EXCEPTION
    WHEN e_listas_vazias THEN
        RAISE_APPLICATION_ERROR(-20001, 'FN_MONTA_JSON: nao ha colunas para converter em JSON.');
    WHEN e_tamanhos_diferentes THEN
        RAISE_APPLICATION_ERROR(-20002, 'FN_MONTA_JSON: quantidade de chaves e valores diferente.');
    WHEN e_tipo_invalido THEN
        RAISE_APPLICATION_ERROR(-20003, 'FN_MONTA_JSON: tipo de campo invalido (use apenas S ou N).');
    WHEN VALUE_ERROR THEN
        RAISE_APPLICATION_ERROR(-20004, 'FN_MONTA_JSON: valor informado como numerico nao e um numero valido.');
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20099, 'FN_MONTA_JSON: erro inesperado - ' || SQLERRM);
END;
/

-- FUNCAO 2: valida a senha de um veterinario (substitui a logica de validacao
-- de senha que hoje ficaria no back-end / TB_VETERINARIO.DsPassword)
CREATE OR REPLACE FUNCTION "FN_VALIDA_SENHA" (
    p_senha IN VARCHAR2
) RETURN VARCHAR2
IS
    e_senha_nula       EXCEPTION;
    e_senha_curta      EXCEPTION;
    e_senha_sem_numero EXCEPTION;
    e_senha_sem_letra  EXCEPTION;
BEGIN
    IF p_senha IS NULL THEN
        RAISE e_senha_nula;
    END IF;

    IF LENGTH(p_senha) < 8 THEN
        RAISE e_senha_curta;
    END IF;

    IF NOT REGEXP_LIKE(p_senha, '[0-9]') THEN
        RAISE e_senha_sem_numero;
    END IF;

    IF NOT REGEXP_LIKE(p_senha, '[A-Za-z]') THEN
        RAISE e_senha_sem_letra;
    END IF;

    RETURN 'SENHA_VALIDA';

EXCEPTION
    WHEN e_senha_nula THEN
        RETURN 'ERRO: senha nao informada.';
    WHEN e_senha_curta THEN
        RETURN 'ERRO: a senha deve ter no minimo 8 caracteres.';
    WHEN e_senha_sem_numero THEN
        RETURN 'ERRO: a senha deve conter ao menos um numero.';
    WHEN e_senha_sem_letra THEN
        RETURN 'ERRO: a senha deve conter ao menos uma letra.';
    WHEN OTHERS THEN
        RETURN 'ERRO: falha inesperada ao validar a senha - ' || SQLERRM;
END;
/

